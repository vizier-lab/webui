/** Seeded value noise in octaves: n×n numbers in 0..1, the same for the same seed and roughness. */
export const GENERATE = `
function hash(x, y, s) {
  var h = (x * 374761393 + y * 668265263 + s * 1274126177) | 0;
  h = (h ^ (h >>> 13)) * 1274126177 | 0;
  h = h ^ (h >>> 16);
  return (h >>> 0) / 4294967295;
}
function smooth(t) { return t * t * (3 - 2 * t); }
function noise(x, y, s) {
  var x0 = Math.floor(x), y0 = Math.floor(y), fx = smooth(x - x0), fy = smooth(y - y0);
  var a = hash(x0, y0, s), b = hash(x0 + 1, y0, s), c = hash(x0, y0 + 1, s), d = hash(x0 + 1, y0 + 1, s);
  return a + (b - a) * fx + (c - a) * fy + (a - b - c + d) * fx * fy;
}
var out = [], octaves = 5, rough = Math.max(0, Math.min(1, roughness));
for (var z = 0; z < n; z++) {
  for (var x = 0; x < n; x++) {
    var v = 0, amp = 1, total = 0, freq = 3;
    for (var o = 0; o < octaves; o++) {
      v += amp * noise(x / n * freq, z / n * freq, seed + o * 17);
      total += amp;
      amp *= rough;
      freq *= 2;
    }
    out.push(Math.max(0, Math.min(1, v / total)));
  }
}
return out;
`

const RUN = (extra: Record<string, unknown> = {}) => ({
    action: 'run',
    params: { fn: 'generate', args: [{ $state: '/seed' }, { $state: '/roughness' }, 48], into: '/_heights' },
    ...extra,
})

export const scene3d: Recipe = {
    intent: 'A 3D terrain you can orbit, regenerated by sliders, computed locally by a logic function.',
    notes: [
        'The terrain is a Heightfield whose heights come from /_heights; keys starting with "_" are derived, not saved.',
        'The Effect fills /_heights when the interface appears; each Slider has a watch that regenerates it, with no round trip to you.',
        'heights must hold resolution² numbers (48×48 here). A flat (default) Heightfield with a low resolution gives the low-poly look.',
        'A Scene3D needs a light; OrbitControls lets the person look around.',
    ],
    spec: {
        root: 'page',
        state: { seed: 7, roughness: 0.55, height: 4, _heights: [] },
        logic: { generate: { params: ['seed', 'roughness', 'n'], body: GENERATE } },
        elements: {
            page: { type: 'Stack', props: { gap: 'md' }, children: ['scene', 'controls', 'boot'] },
            scene: { type: 'Scene3D', props: { height: 380, camera: { position: [38, 30, 38], fov: 45 } }, children: ['sun', 'ambient', 'land', 'orbit'] },
            land: {
                type: 'Heightfield',
                props: {
                    size: [60, 60],
                    resolution: 48,
                    heights: { $state: '/_heights' },
                    heightScale: { $state: '/height' },
                    flat: true,
                    palette: [{ at: 0, color: '#2b5d7a' }, { at: 0.3, color: '#4f8f4a' }, { at: 0.7, color: '#8a7d63' }, { at: 1, color: '#f2f4f7' }],
                },
            },
            sun: { type: 'DirectionalLight', props: { position: [20, 40, 10], intensity: 1.1 } },
            ambient: { type: 'AmbientLight', props: { intensity: 0.45 } },
            orbit: { type: 'OrbitControls', props: { autoRotate: false } },
            controls: { type: 'Grid', props: { cols: 3, gap: 'md', minCol: 160 }, children: ['seed', 'rough', 'tall'] },
            seed: { type: 'Slider', props: { label: 'Seed', min: 1, max: 99, step: 1, value: { $bindState: '/seed' } }, watch: { '/seed': RUN() } },
            rough: { type: 'Slider', props: { label: 'Roughness', min: 0, max: 1, step: 0.05, value: { $bindState: '/roughness' } }, watch: { '/roughness': RUN() } },
            tall: { type: 'Slider', props: { label: 'Height', min: 1, max: 12, step: 0.5, value: { $bindState: '/height' } } },
            boot: { type: 'Effect', props: {}, on: { load: RUN() } },
        },
    },
}
